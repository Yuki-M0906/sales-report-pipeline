# -*- coding: utf-8 -*-
"""仕入先の変換部品のひな形。

使い方:
1. このファイルを  process_<英数字の名前>.py  という名前でコピーする (例: process_abc_trading.py)。
   名前が process_ で始まらないファイル (このひな形など) は、変換部品として扱われない。
2. SUPPLIER_NAME を仕入先の名前にする。この名前が
   - 入力フォルダの名前  (<入力データのルート>/<SUPPLIER_NAME>/input/)
   - 出力の「卸名」
   - ID マスタの「卸マスタ」で卸 ID を引くキー
   になる。
3. load_file() の中身を、その仕入先のファイルの形に合わせて書く。

load_file(path) の約束:
- 引数は 1 つの xlsx ファイルのパス。
- 戻り値は「1 行 = 1 得意先 × 1 商品」の表 (pandas の DataFrame)。列は次の名前にする。
      必須: 得意先名称、商品名称、販売本数
      任意: 容量、入数、住所、業態、計上月
  これ以外の名前の列を返すとエラーになる (列名の書き間違いに気づけるように)。
- 値はきれいにしなくてよい。前後の空白の除去、"1,200" → 1200、"1.8L" → 1800 などは後の工程が行う。
- 明細でない行 (合計・小計・注記) は、ここで取り除く。
- 計上月は、ファイル名の先頭 6 桁 (例: 202610_xxx.xlsx) から自動で付く。
  ファイルの中に年月があり、そちらを使いたい場合だけ「計上月」列 (YYYYMM) を返す。
- 読めない・想定と違うと分かったら、例外を出す (黙って空の表を返さない)。
  そのファイルは取り込まれず、画面に「要確認」として表示される。
"""

from pipeline_app import plugin

SUPPLIER_NAME = "ここに仕入先名"


def load_file(path):
    # 見出しが 1 行目にあるシートを読む (見出しが 3 行目にあるなら header_row=3)
    df = plugin.read_sheet(path, sheet=0, header_row=1)

    # 必要な列を取り出して、標準形式の列名に付け替える  {標準形式の列名: このファイルでの見出し}
    df = plugin.select(df, {
        "得意先名称": "得意先",
        "商品名称": "商品",
        "販売本数": "数量",
        # "容量": "規格",
        # "入数": "入数",
        # "住所": "住所",
        # "業態": "業態",
    })

    # 合計行などを取り除く (必要な場合)
    # df = plugin.drop_rows_containing(df, "得意先名称", ["合計", "小計"])
    return df
